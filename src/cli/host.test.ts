describe("parseRunArgs", () => {
  test("defaults to no port override and read-only host tools", () => {
    const a = parseRunArgs([]);
    expect(a.port).toBeUndefined();
    expect(a.allowWrite).toBe(false);
    expect(a.allowExec).toBe(false);
    expect(a.cliArgv).toEqual([]);
  });

  test("accepts both --flag value and --flag=value", () => {
    expect(parseRunArgs(["--port", "9000"]).port).toBe(9000);
    expect(parseRunArgs(["--port=9000"]).port).toBe(9000);
  });

  test("passes everything after -- to cli.ts", () => {
    const a = parseRunArgs(["--port", "9000", "--", "--mine", "x"]);
    expect(a.port).toBe(9000);
    expect(a.cliArgv).toEqual(["--mine", "x"]);
  });

  test("rejects an unknown flag rather than silently ignoring it", () => {
    // A mistyped `--prot 8787` handed to cli.ts would bind the default port
    // and look like it worked.
    expect(() => parseRunArgs(["--nope"])).toThrow(/unknown option/);
    expect(() => parseRunArgs(["--prot", "8787"])).toThrow(/unknown option/);
  });

  test("passes positionals through to cli.ts without needing --", () => {
    // `bun run start -- list` has its `--` eaten by Bun, so ayjnt receives
    // `run list`. Rejecting that broke the documented invocation.
    expect(parseRunArgs(["list"]).cliArgv).toEqual(["list"]);
    expect(parseRunArgs(["add", "hello", "world"]).cliArgv).toEqual([
      "add",
      "hello",
      "world",
    ]);
  });

  test("mixes flags and positionals in either order", () => {
    const a = parseRunArgs(["--port", "9000", "add", "hi"]);
    expect(a.port).toBe(9000);
    expect(a.cliArgv).toEqual(["add", "hi"]);

    const b = parseRunArgs(["add", "hi", "--port", "9000"]);
    expect(b.port).toBe(9000);
    expect(b.cliArgv).toEqual(["add", "hi"]);
  });

  test("positionals and post-separator args both reach cli.ts, in order", () => {
    const a = parseRunArgs(["tool", "--port", "9000", "--", "--json"]);
    expect(a.port).toBe(9000);
    expect(a.cliArgv).toEqual(["tool", "--json"]);
  });

  test("rejects a non-numeric or out-of-range port", () => {
    expect(() => parseRunArgs(["--port", "abc"])).toThrow(/--port/);
    expect(() => parseRunArgs(["--port", "99999"])).toThrow(/--port/);
  });

  test("rejects a flag whose value is missing", () => {
    expect(() => parseRunArgs(["--port"])).toThrow(/requires a value/);
  });

  test("allows port 0 for an ephemeral port", () => {
    expect(parseRunArgs(["--port", "0"]).port).toBe(0);
  });

  test("host effect flags are opt-in", () => {
    const a = parseRunArgs(["--allow-host-writes", "--allow-host-exec"]);
    expect(a.allowWrite).toBe(true);
    expect(a.allowExec).toBe(true);
  });
});

