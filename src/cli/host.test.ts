describe("parseGeneratedConfig", () => {
  test("strips the generated header comment", () => {
    const cfg = parseGeneratedConfig(
      '// GENERATED by ayjnt — do not edit.\n{ "name": "app" }\n',
    );
    expect(cfg.name).toBe("app");
  });

  test("keeps a // inside a string value intact", () => {
    // Only whole-line comments are stripped. A naive `//`-to-end-of-line strip
    // would corrupt any URL a user put in `vars`.
    const cfg = parseGeneratedConfig(
      '// header\n{ "name": "app", "vars": { "API": "https://example.com/x" } }',
    );
    expect((cfg.vars as Record<string, string>)["API"]).toBe(
      "https://example.com/x",
    );
  });

  test("reads the bindings the local runtime cares about", () => {
    const cfg = parseGeneratedConfig(`// h
{
  "name": "app",
  "durable_objects": { "bindings": [{ "name": "CHAT_AGENT", "class_name": "ChatAgent" }] },
  "workflows": [{ "name": "importer", "binding": "IMPORTER", "class_name": "Importer" }],
  "assets": { "directory": "../assets", "binding": "ASSETS", "html_handling": "none" }
}`);
    expect(cfg.durable_objects?.bindings[0]?.class_name).toBe("ChatAgent");
    expect(cfg.workflows?.[0]?.binding).toBe("IMPORTER");
    expect(cfg.assets?.html_handling).toBe("none");
  });
});

describe("parseDevVars", () => {
  test("parses simple assignments and skips comments and blanks", () => {
    expect(parseDevVars("A=1\n\n# note\nB=two\n")).toEqual({
      A: "1",
      B: "two",
    });
  });

  test("strips one layer of matching quotes", () => {
    expect(parseDevVars(`A="quoted"\nB='single'`)).toEqual({
      A: "quoted",
      B: "single",
    });
  });

  test("keeps = inside a value", () => {
    expect(parseDevVars("TOKEN=abc=def==")).toEqual({ TOKEN: "abc=def==" });
  });

  test("ignores a line with no key", () => {
    expect(parseDevVars("=novalue\nA=1")).toEqual({ A: "1" });
  });
});

describe("resolveUrl", () => {
  test("resolves a path against the origin", () => {
    expect(resolveUrl("http://localhost:8787", "/counter/demo")).toBe(
      "http://localhost:8787/counter/demo",
    );
  });

  test("adds the missing leading slash", () => {
    expect(resolveUrl("http://localhost:8787", "counter")).toBe(
      "http://localhost:8787/counter",
    );
  });

  test("leaves an absolute URL alone", () => {
    expect(resolveUrl("http://localhost:8787", "https://example.com/x")).toBe(
      "https://example.com/x",
    );
  });
});

